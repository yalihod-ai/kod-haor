function compute(){
  const s={h:0,a:0,p:0,o:0};
  Q.forEach(function(q,i){const a=ans[i];const idxs=Array.isArray(a)?a:[a];
    idxs.forEach(function(ix){const sc=q.o[ix][1];for(const k in sc)s[k]+=sc[k];});
    if(q.active && Array.isArray(a)){
      const activeIdx=[1,2,3,4,5,6,7]; // ויטמין C .. חומצה אזלאית
      const chosen=a.filter(function(x){return activeIdx.includes(x)});
      if(chosen.length>=4) s.o+=3;
      if(a.includes(2)&&a.includes(4)) s.o+=2; // רטינול + חומצות
    }
  });
  return s;
}
